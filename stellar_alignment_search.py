#!/usr/bin/env python3
"""Catalogue-based stellar comparisons on solar-selected nighttime windows.

Skyfield apparent topocentric directions without refraction, explicit ICRS
position epochs/proper motions, and zero parallax/radial velocity. Library use
and numerical convergence do not certify ancient-epoch astronomical accuracy.
"""
import argparse
import csv
import importlib.metadata
import math
from pathlib import Path
import json
from pyramid_solar_alignment import DAY, Engine, number, digest, save_csv, save_json, julian_label

TARGETS = {'Kings':{25930,26311,26727}, 'Queens':{32349}}
NAMES = {25930:'Mintaka',26311:'Alnilam',26727:'Alnitak',32349:'Sirius'}


def catalogue(path, limit=2.5, expected=None):
    selected, seen, excluded = [], set(), 0
    with Path(path).open(newline='',encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        required = {'HIP','RAICRS','DEICRS','pmRA','pmDE','Vmag'}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError(f'Required catalogue columns: {sorted(required)}')
        for row in reader:
            if number(row['Vmag']) >= limit:
                excluded += 1
                continue
            values = {k:number(row[k]) for k in required}
            hip = int(values['HIP'])
            if hip <= 0 or hip != values['HIP'] or hip in seen:
                raise ValueError('Invalid or duplicate HIP identifier')
            if not 0 <= values['RAICRS'] < 360 or not -90 < values['DEICRS'] < 90:
                raise ValueError(f'Invalid/polar catalogue coordinates: HIP {hip}')
            seen.add(hip)
            values.update({'HIP':hip,'epoch_jyear':number(row.get('epoch_jyear') or 1991.25),'name':row.get('name') or NAMES.get(hip,f'HIP {hip}')})
            selected.append(values)
    if not selected or expected is not None and len(selected) != expected:
        raise ValueError(f'Catalogue count {len(selected)} does not meet requested selection')
    return selected, excluded


def vector(alt, az):
    h, a = map(math.radians,(alt,az))
    return math.cos(h)*math.sin(a), math.cos(h)*math.cos(a), math.sin(h)


def separation(alt, az, target_alt, target_az):
    u, v = vector(alt,az), vector(target_alt,target_az)
    cross = (u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0])
    return math.degrees(math.atan2(math.sqrt(sum(x*x for x in cross)),sum(x*y for x,y in zip(u,v))))


def grid_times(duration, step):
    duration, step = number(duration), number(step)
    if duration <= 0 or step <= 0:
        raise ValueError('Positive duration/step required')
    times = [i*step for i in range(math.floor(duration/step)+1)]
    if times[-1] != duration:
        times.append(duration)
    return times


def minimize(evaluate, duration, step=60.0, tolerance=0.01):
    from scipy.optimize import minimize_scalar
    tolerance = number(tolerance)
    if tolerance <= 0:
        raise ValueError('Positive refinement tolerance required')
    times = grid_times(duration,step)
    values = [evaluate(t) for t in times]
    for row in values:
        number(row['separation_deg'])
    i = min(range(len(times)),key=lambda k:values[k]['separation_deg'])
    brackets = {(times[0],times[1]),(times[-2],times[-1])}
    for k in range(1,len(times)-1):
        if values[k]['separation_deg'] <= min(values[k-1]['separation_deg'],values[k+1]['separation_deg']):
            brackets.add((times[k-1],times[k+1]))
    candidates = [(times[0],values[0]),(times[-1],values[-1]),(times[i],values[i])]
    for a,b in sorted(brackets):
        fit = minimize_scalar(lambda t:number(evaluate(float(t))['separation_deg']),bounds=(a,b),method='bounded',options={'xatol':tolerance,'maxiter':200})
        if not fit.success:
            raise RuntimeError(f'Nonconvergent local minimum: {fit.message}')
        candidates.append((float(fit.x),evaluate(float(fit.x))))
    t, best = min(candidates,key=lambda pair:pair[1]['separation_deg'])
    return {**best,'seconds_from_start':t,'boundary':t == 0 or t == duration,
            'distance_to_edge_seconds':min(t,duration-t),'grid_separation_deg':values[i]['separation_deg'],
            'grid_excess_deg':values[i]['separation_deg']-best['separation_deg'],'grid_samples':len(times)}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--ephemeris',required=True)
    p.add_argument('--catalogue',required=True,help='Archived CSV; no automatic downloads or fallback')
    p.add_argument('--windows-json',required=True,help='Generated by the solar script')
    p.add_argument('--output-dir',default='results/stellar')
    p.add_argument('--vmag-limit',type=float,default=2.5)
    p.add_argument('--expected-count',type=int)
    p.add_argument('--grid-seconds',type=float,default=60)
    p.add_argument('--tolerance-seconds',type=float,default=0.01)
    p.add_argument('--azimuth',type=float,help='Stellar direction override only; scalar solar roots unchanged')
    a = p.parse_args()
    stars, excluded = catalogue(a.catalogue,number(a.vmag_limit),a.expected_count)
    doc = json.loads(Path(a.windows_json).read_text())
    if doc.get('schema') != 'pyramid-windows-v2' or not doc.get('windows'):
        raise ValueError('Use windows generated by the solar pipeline')
    config = doc['metadata']
    if digest(a.ephemeris) != config['kernel_sha256']:
        raise ValueError('Solar and stellar kernel hashes differ')
    ids = {row['HIP'] for row in stars}
    for window in doc['windows']:
        if window['chamber'] not in TARGETS or not TARGETS[window['chamber']].issubset(ids):
            raise ValueError('Required historical targets missing from the same magnitude-limited catalogue')
    engine = Engine(a.ephemeris,config['latitude_deg'],config['longitude_deg_east'],config['delta_t_seconds'])
    try:
        from skyfield.api import Star
        objects = [(r,Star(ra_hours=r['RAICRS']/15,dec_degrees=r['DEICRS'],ra_mas_per_year=r['pmRA'],dec_mas_per_year=r['pmDE'],epoch=2451545+(r['epoch_jyear']-2000)*365.25,parallax_mas=0,radial_km_per_s=0)) for r in stars]
        results, targets = [], []
        for w in doc['windows']:
            start, end, alpha = map(number,(w['start_jd_ut1'],w['end_jd_ut1'],w['elevation_deg']))
            duration = (end-start)*DAY
            azimuth = number(a.azimuth if a.azimuth is not None else w['azimuth_deg'])%360
            if not 0 < duration <= 2*DAY or not 0 < alpha < 90:
                raise ValueError('Invalid window/elevation')
            case = []
            for entry, star in objects:
                def evaluate(seconds):
                    ut = start+seconds/DAY
                    t = engine.ts.ut1_jd(ut)
                    apparent = engine.observer.at(t).observe(star).apparent()
                    alt, az, _ = apparent.altaz()
                    ra, dec, _ = apparent.radec(epoch='date')
                    h, z = float(alt.degrees),float(az.degrees)
                    return {'jd_ut1':ut,'jd_tt':float(t.tt),'altitude_deg':h,'azimuth_deg':z,'apparent_ra_deg':float(ra.hours)*15,'apparent_dec_deg':float(dec.degrees),'altitude_residual_deg':h-alpha,'azimuth_residual_deg':(z-azimuth+180)%360-180,'separation_deg':separation(h,z,alpha,azimuth)}
                best = minimize(evaluate,duration,a.grid_seconds,a.tolerance_seconds)
                case.append({'case_id':w['case_id'],'window_label':w['local_midnight_label'],'chamber':w['chamber'],'rank':0,'HIP':entry['HIP'],'name':entry['name'],'Vmag':entry['Vmag'],'elevation_deg':alpha,'shaft_azimuth_deg':azimuth,**best,'local_mean_label':julian_label(best['jd_ut1']+engine.lon/360,'local mean solar time')})
            case.sort(key=lambda row:(row['separation_deg'],row['HIP']))
            for rank, row in enumerate(case,1):
                row['rank'] = rank
                results.append(row)
                if row['HIP'] in TARGETS[w['chamber']]:
                    targets.append(dict(row))
        out = Path(a.output_dir)
        out.mkdir(parents=True,exist_ok=True)
        save_csv(out/'ranked_stellar_results.csv',results)
        save_csv(out/'historical_targets.csv',targets)
        metadata = engine.metadata()
        metadata.update({'script_sha256':digest(__file__),'catalogue_sha256':digest(a.catalogue),'windows_sha256':digest(a.windows_json),'count':len(stars),'selected_HIP':sorted(ids),'excluded_by_magnitude':excluded,'strict_Vmag_limit':a.vmag_limit,'epoch_default_jyear':1991.25,'stellar_frame':'Skyfield apparent topocentric, no refraction','proper_motion':'catalogue pmRA*cos(dec) and pmDE in mas/year; explicit position epoch','parallax_mas':0,'radial_km_per_s':0,'grid_seconds':a.grid_seconds,'refinement_tolerance_seconds':a.tolerance_seconds,'azimuth_override':a.azimuth,'scipy':importlib.metadata.version('scipy'),'minimization':'exact endpoints plus local and boundary-adjacent refinement; small brackets assumed unimodal'})
        save_json(out/'run_metadata.json',metadata)
        print(f'Wrote {len(results)} results from {len(stars)} catalogue stars')
    finally:
        engine.eph.close()


if __name__ == '__main__':
    main()
